<?php

declare(strict_types=1);

namespace Masilia\IbexaAi\Os\Capability\Url;

use Masilia\IbexaAi\Os\Capability\RepositoryCapability;
use Masilia\Contracts\IbexaAi\Os\CapabilityResult;
use Masilia\Contracts\IbexaAi\Os\Preview;
use Masilia\Contracts\IbexaAi\Os\Risk;

final class AliasRemoveCapability extends RepositoryCapability
{
    public function name(): string
    {
        return 'url.alias.remove';
    }

    public function summary(): string
    {
        return 'Remove a custom URL.';
    }

    public function description(): string
    {
        return 'Removes a custom alias (see url.alias.list): the path stops answering. System aliases cannot be removed.';
    }

    public function inputSchema(): array
    {
        return ['type' => 'object', 'required' => ['alias_id'], 'properties' => ['alias_id' => ['type' => 'string', 'minLength' => 1]]];
    }

    public function risk(): Risk
    {
        return Risk::DESTRUCTIVE;
    }

    public function requires(): array
    {
        return [['content', 'urltranslator']];
    }

    public function examples(): array
    {
        return [['description' => 'Remove a short URL', 'arguments' => ['alias_id' => '1364-abc']]];
    }

    public function validate(array $arguments): ?string
    {
        try {
            $alias = $this->repository->getURLAliasService()->load((string) $arguments['alias_id']);
        } catch (\Throwable) {
            return sprintf('There is no alias "%s": see url.alias.list.', $arguments['alias_id']);
        }

        return $alias->isCustom ? null : 'Only a custom alias can be removed: that one is generated by the system.';
    }

    public function preview(array $arguments): Preview
    {
        return new Preview('Remove a URL', [['Alias', (string) $arguments['alias_id']]], ['Visitors using this URL get a "not found". This cannot be undone.']);
    }

    public function execute(array $arguments): CapabilityResult
    {
        $service = $this->repository->getURLAliasService();
        $alias = $service->load((string) $arguments['alias_id']);
        $service->removeAliases([$alias]);

        return CapabilityResult::ok(sprintf('The URL "%s" was removed', $alias->path), []);
    }
}
